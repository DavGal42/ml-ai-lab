import torch
import torch.nn as nn
import torch.optim as optim


# -----------------------------------------------------------
# СОЗДАНИЕ ОБУЧАЮЩИХ ДАННЫХ
# -----------------------------------------------------------

# создаём случайные входные данные
# torch.rand(100,2) означает:
# 100 строк (100 примеров обучения)
# 2 столбца (два входных параметра x1 и x2)
x_train = torch.rand(100, 2) * 10

# создаём правильный ответ (target)
# y_train содержит правильный ответ для каждого примера
y_train = x_train[:,0:1] + x_train[:,1:2]


# -----------------------------------------------------------
# СОЗДАНИЕ НЕЙРОСЕТИ
# -----------------------------------------------------------

# nn.Sequential позволяет построить модель из слоёв последовательно
# данные проходят слой за слоем
model = nn.Sequential(

    # первый слой нейросети
    # nn.Linear(2,2) означает:
    #
    # 2 входа (x1 и x2)
    # 2 нейрона в слое
    #
    # каждый нейрон считает:
    #
    # z = w1*x1 + w2*x2 + b
    #
    nn.Linear(2,2),

    # функция активации ReLU
    # она делает:
    #
    # f(z) = max(0,z)
    #
    # если z < 0 → результат 0
    # если z > 0 → результат z
    #
    # это добавляет нелинейность нейросети
    nn.ReLU(),

    # второй слой нейросети
    #
    # nn.Linear(2,1)
    #
    # 2 входа (выходы предыдущих нейронов)
    # 1 нейрон на выходе
    #
    # этот нейрон выдаёт итоговое предсказание y_pred
    nn.Linear(2,1)
)


# -----------------------------------------------------------
# ФУНКЦИЯ ОШИБКИ (LOSS FUNCTION)
# -----------------------------------------------------------

# используем MSE (Mean Squared Error)
#
# формула:
#
# loss = (y - y_pred)^2
#
# это показывает насколько модель ошибается
loss_fn = nn.MSELoss()


# -----------------------------------------------------------
# ОПТИМИЗАТОР
# -----------------------------------------------------------

# используем SGD (Stochastic Gradient Descent)
# алгоритм обновления весов
#
# формула обновления:
#
# w_new = w_old - lr * gradient
#
# lr = learning rate (скорость обучения)
optimizer = optim.SGD(model.parameters(), lr=0.01)


# -----------------------------------------------------------
# ОБУЧЕНИЕ НЕЙРОСЕТИ
# -----------------------------------------------------------

# epoch = один полный проход по всем данным
# делаем 2000 итераций обучения
for epoch in range(2000):

    # -------------------------------------------------------
    # FORWARD PASS
    # -------------------------------------------------------

    # пропускаем данные через модель
    # нейросеть делает предсказание
    y_pred = model(x_train)


    # -------------------------------------------------------
    # ВЫЧИСЛЯЕМ ОШИБКУ
    # -------------------------------------------------------

    # сравниваем правильный ответ y_train
    # и предсказание модели y_pred
    loss = loss_fn(y_pred, y_train)


    # -------------------------------------------------------
    # ОЧИЩАЕМ СТАРЫЕ ГРАДИЕНТЫ
    # -------------------------------------------------------

    # PyTorch накапливает градиенты
    # поэтому перед новым вычислением их нужно очистить
    optimizer.zero_grad()


    # -------------------------------------------------------
    # BACKPROPAGATION
    # -------------------------------------------------------

    # вычисляем градиенты автоматически
    #
    # PyTorch считает:
    #
    # dL/dw
    # dL/db
    #
    # для всех весов сети
    loss.backward()


    # -------------------------------------------------------
    # ОБНОВЛЕНИЕ ВЕСОВ
    # -------------------------------------------------------

    # optimizer.step() изменяет веса модели
    #
    # используется формула:
    #
    # w_new = w_old - lr * gradient
    optimizer.step()


    # -------------------------------------------------------
    # ВЫВОД ОШИБКИ
    # -------------------------------------------------------

    # каждые 200 эпох выводим значение ошибки
    if epoch % 200 == 0:
        print("loss:", loss.item())


# -----------------------------------------------------------
# ТЕСТ МОДЕЛИ
# -----------------------------------------------------------

# создаём новый пример
# модель его раньше не видела
x_test = torch.tensor([[10.0,7.0]])

# отключаем вычисление градиентов
# это ускоряет работу и экономит память
with torch.no_grad():

    # получаем предсказание модели
    prediction = model(x_test)


# выводим результат
print("Prediction:", prediction)